const dicts: Record<Lang, Dict> = { en, ku, ar };

type I18nContextType = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  dir: "ltr" | "rtl";
};

const I18nContext = createContext<I18nContextType | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");

  useEffect(() => {
    const saved = typeof window !== "undefined" ? (localStorage.getItem("nuva-lang") as Lang | null) : null;
    if (saved && ["en", "ku", "ar"].includes(saved)) setLang(saved);
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      const dir = dicts[lang].dir as "ltr" | "rtl";
      document.documentElement.lang = lang;
      document.documentElement.dir = dir;
    }
    if (typeof window !== "undefined") localStorage.setItem("nuva-lang", lang);
  }, [lang]);

  const value = useMemo<I18nContextType>(() => {
    const dict = dicts[lang];
    return {
      lang,
      setLang,
      t: (key: string) => dict[key] ?? en[key] ?? key,
      dir: dict.dir as "ltr" | "rtl",
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

